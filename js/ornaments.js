/* Header / login ornament: chosen by the ADMIN only, for every device.
   The patterns are in css/ornaments.css (generated by scripts/gen-ornaments.js);
   this file sets html[data-ornament] (+ --orn-size / --orn-x / --orn-y for the drawing:
   which part of the picture shows and how big) and draws the admin's controls (admin page).
   The choice is saved in app_settings key "header_ornament" = { id, size, x, y } (every
   signed-in user reads it, only the admin may write it — the database refuses anyone
   else) and cached on the device for the next start. Stars (the original) = no attribute. */
(function (global) {
  "use strict";
  var CACHE = "pharma.ornament", PCACHE = "pharma.ornament.pos", SKEY = "header_ornament";
  var DEF = { size: 700, x: 50, y: 50 };
  var LIST = [{"id":"","name":"نجوم"},{"id":"art","name":"خطوط منسابة"},{"id":"khatam","name":"ختم سليماني"},{"id":"rosette","name":"وردة اثنا عشرية"},{"id":"arabesque","name":"أرابيسك نباتي"},{"id":"zellige","name":"زليج مغربي"},{"id":"arches","name":"شبكة عقود"},{"id":"medallion","name":"ميدالية بتلات"}];
  var root = document.documentElement;
  var pos = { size: DEF.size, x: DEF.x, y: DEF.y };

  function cached() { try { return localStorage.getItem(CACHE) || ""; } catch (e) { return ""; } }
  function cache(id) { try { localStorage.setItem(CACHE, id); } catch (e) { /* blocked */ } }
  function valid(id) { return LIST.some(function (p) { return p.id === id; }); }
  function clamp(v, lo, hi, d) { v = Number(v); return isFinite(v) ? Math.min(hi, Math.max(lo, v)) : d; }
  function norm(p) {
    p = p || {};
    return { size: clamp(p.size, 300, 1600, DEF.size), x: clamp(p.x, 0, 100, DEF.x), y: clamp(p.y, 0, 100, DEF.y) };
  }
  function cachedPos() { try { return norm(JSON.parse(localStorage.getItem(PCACHE) || "null")); } catch (e) { return norm(); } }

  function applyPos(p) {
    pos = norm(p);
    root.style.setProperty("--orn-size", pos.size + "px");
    root.style.setProperty("--orn-x", pos.x + "%");
    root.style.setProperty("--orn-y", pos.y + "%");
    var set = function (id, v, out) {
      var el = document.getElementById(id), o = document.getElementById(out);
      if (el && document.activeElement !== el) el.value = v;
      if (o) o.textContent = id === "orn-size" ? v + "px" : v + "%";
    };
    set("orn-size", pos.size, "orn-size-v"); set("orn-x", pos.x, "orn-x-v"); set("orn-y", pos.y, "orn-y-v");
  }

  function apply(id) {
    if (id === undefined) id = cached();
    if (!valid(id)) id = "";
    if (id) root.setAttribute("data-ornament", id); else root.removeAttribute("data-ornament");
    var row = document.getElementById("ornament-chips");
    if (row) Array.prototype.forEach.call(row.children, function (b) {
      var on = b.getAttribute("data-id") === id;
      b.classList.toggle("is-on", on);
      b.setAttribute("aria-pressed", on ? "true" : "false");
    });
    var box = document.getElementById("orn-pos");          // the size / position controls: the drawing only
    if (box) box.hidden = id !== "art";
    var pv = document.getElementById("orn-preview");
    if (pv) pv.hidden = !id;
  }

  var client = function () {
    var SB = global.PharmacySupabase;
    return SB && SB.isConfigured() ? SB.getClient() : null;
  };
  var channel = null;

  async function load() {
    var c = client();
    if (!c) return;
    try {
      var r = await c.from("app_settings").select("value").eq("key", SKEY).maybeSingle();
      if (r.error) return;
      var v = r.data && r.data.value ? (typeof r.data.value === "string" ? JSON.parse(r.data.value) : r.data.value) : null;
      cache(v && valid(v.id) ? v.id : "");           // no row = the stars
      var p = norm(v);
      try { localStorage.setItem(PCACHE, JSON.stringify(p)); } catch (e) { /* blocked */ }
      applyPos(p);
      apply();
    } catch (e) { /* offline / table missing: keep the cached choice */ }
  }

  function start() {
    load();
    var c = client();
    if (c && !channel) {
      try {
        channel = c.channel("pharma-ornament")
          .on("postgres_changes", { event: "*", schema: "public", table: "app_settings" }, function () { load(); })
          .subscribe();
      } catch (e) { /* the visibility refresh below still picks it up */ }
    }
  }

  // Admin only (also enforced by the database)
  async function save(id, p) {
    var A = global.PharmacyAuth;
    if (!(A && A.isAdmin && A.isAdmin())) return { ok: false, error: "تغيير الزخرفة للمسؤول فقط" };
    if (!valid(id)) return { ok: false, error: "قيمة غير معروفة" };
    var c = client();
    if (!c) return { ok: false, error: "غير متصل" };
    p = norm(p);
    var r = await c.from("app_settings").upsert({ key: SKEY, value: { id: id, size: p.size, x: p.x, y: p.y }, updated_at: new Date().toISOString() }, { onConflict: "key" });
    if (r.error) return { ok: false, error: r.error.message || "تعذّر الحفظ" };
    cache(id);
    try { localStorage.setItem(PCACHE, JSON.stringify(p)); } catch (e) { /* blocked */ }
    applyPos(p);
    apply();
    return { ok: true };
  }
  function flash(res, text) {
    var f = global.PharmacyApp && global.PharmacyApp.flashHint;
    if (f) f(res.ok ? text : "تعذّر الحفظ: " + res.error);
  }

  function render() {
    var row = document.getElementById("ornament-chips");
    if (!row || row.children.length) return;
    LIST.forEach(function (p) {
      var b = document.createElement("button");
      b.type = "button";
      b.className = "orn-chip";
      b.setAttribute("data-id", p.id);
      b.textContent = p.name;
      b.addEventListener("click", async function () {
        flash(await save(p.id, pos), "✓ زخرفة الشريط: " + p.name + " (لكل الأجهزة)");
      });
      row.appendChild(b);
    });
    // size / position sliders: live while dragging, saved on release
    var read = function () {
      return { size: document.getElementById("orn-size").value, x: document.getElementById("orn-x").value, y: document.getElementById("orn-y").value };
    };
    ["orn-size", "orn-x", "orn-y"].forEach(function (id) {
      var el = document.getElementById(id);
      if (!el) return;
      el.addEventListener("input", function () { applyPos(read()); });
      el.addEventListener("change", async function () { flash(await save(cached(), read()), "✓ حُفظ حجم الزخرفة وموضعها (لكل الأجهزة)"); });
    });
    var reset = document.getElementById("orn-reset");
    if (reset) reset.addEventListener("click", async function () { flash(await save(cached(), DEF), "✓ أُعيد الضبط (لكل الأجهزة)"); });
    applyPos(cachedPos());
    apply();
  }

  applyPos(cachedPos());
  apply();
  document.addEventListener("DOMContentLoaded", render);
  if (document.readyState !== "loading") render();
  document.addEventListener("visibilitychange", function () { if (!document.hidden) load(); });
  global.PharmacyOrnaments = { apply: apply, choose: function (id) { return save(id, pos); }, start: start, load: load, list: LIST };
})(window);
