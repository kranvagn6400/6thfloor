/* Colour themes: every user picks one for themselves (kept on this device).
   The colours are in css/palettes.css (generated by scripts/gen-palettes.js);
   this file sets html[data-palette] and draws the swatches in the settings page.
   Emerald (the default) = no attribute. */
(function (global) {
  "use strict";
  var KEY = "pharma.palette";
  var LIST = [{"id":"","name":"زمردي","c":"#17433D","c2":"#1D9E75"},{"id":"sky6","name":"أبيض وسماوي","c":"#1c6492","c2":"#6dc0f3"},{"id":"violet","name":"بنفسجي","c":"#33214f","c2":"#6537ae"},{"id":"pink","name":"وردي داكن","c":"#541c33","c2":"#ba2c65"},{"id":"cyan","name":"سماوي","c":"#184b58","c2":"#20a4c5"},{"id":"charcoal","name":"رمادي فحمي","c":"#33373d","c2":"#657081"},{"id":"teal","name":"فيروزي","c":"#155b56","c2":"#19ccc0"},{"id":"purple","name":"أرجواني","c":"#461c54","c2":"#962cba"},{"id":"lilac","name":"ليلكي","c":"#77478f","c2":"#dec9e9"},{"id":"skyblue","name":"أزرق سماوي","c":"#182c58","c2":"#2054c5"},{"id":"classic","name":"الأزرق القديم","c":"#132a5d","c2":"#2563EB"},{"id":"black","name":"أسود","c":"#171717","c2":"#303030"}];
  var root = document.documentElement;

  // 6th Floor: white + sky blue unless the user picked another (an explicit "" = emerald)
  function saved() { try { var v = localStorage.getItem(KEY); return v === null ? "sky6" : v; } catch (e) { return "sky6"; } }
  function valid(id) { return LIST.some(function (p) { return p.id === id; }); }

  function apply(id) {
    if (!valid(id)) id = "";
    if (id) root.setAttribute("data-palette", id); else root.removeAttribute("data-palette");
    var meta = document.querySelector('meta[name="theme-color"]');
    var p = LIST.filter(function (x) { return x.id === id; })[0];
    if (meta && p) meta.setAttribute("content", p.c);
    var row = document.getElementById("palette-swatches");
    if (row) Array.prototype.forEach.call(row.children, function (b) {
      var on = b.getAttribute("data-id") === id;
      b.classList.toggle("is-on", on);
      b.setAttribute("aria-pressed", on ? "true" : "false");
    });
  }

  function choose(id) {
    try { localStorage.setItem(KEY, id); } catch (e) { /* blocked */ }
    apply(id);
  }

  function render() {
    var row = document.getElementById("palette-swatches");
    if (!row || row.children.length) return;
    LIST.forEach(function (p) {
      var b = document.createElement("button");
      b.type = "button";
      b.className = "palette-swatch";
      b.setAttribute("data-id", p.id);
      b.setAttribute("aria-label", p.name);
      b.title = p.name;
      b.style.background = "linear-gradient(135deg," + p.c2 + " 0%," + p.c + " 100%)";
      b.addEventListener("click", function () { choose(p.id); });
      row.appendChild(b);
    });
    apply(saved());
  }

  apply(saved());
  document.addEventListener("DOMContentLoaded", render);
  if (document.readyState !== "loading") render();
  global.PharmacyPalettes = { apply: apply, choose: choose, list: LIST };
})(window);
